import type { NpcScript, Reaction } from './npcScripts';
import type { EndingId } from './story';
import type { CardId, CharId, Character, Claim } from './types';

export type VariantId = 'v0' | 'v1' | 'v2';
export const VARIANT_IDS: VariantId[] = ['v0', 'v1', 'v2'];

export interface DefenseItem {
  label: string;
  cards: CardId[];
}

export interface CaseVariant {
  id: VariantId;
  /** 엔딩 전까지 보이는 이름 (스포일러 없음) */
  code: string;
  /** 엔딩에서 공개되는 부제 */
  title: string;
  culprit: CharId;
  /** MOTIVE_OPTIONS 중 정답 */
  motive: string;
  /** 보고서 증거 점수: 이 중 2장 이상을 근거로 들면 1점 */
  keyChain: CardId[];
  /** NPC 투표: 이 중 2장 이상이 공개되면 진범에게 투표한다 */
  voteChain: CardId[];
  cards: Partial<Record<CardId, { text?: string; note?: string }>>;
  characters: Partial<Record<CharId, Partial<Omit<Character, 'id' | 'name' | 'color' | 'mbti' | 'gender'>>>>;
  scripts: Partial<Record<CharId, NpcScript>>;
  claims: Partial<Record<string, Pick<Claim, 'contradictedBy' | 'verifiedBy'>>>;
  defense: Partial<Record<CharId, DefenseItem[]>>;
  suspicion: Partial<Record<CardId, CharId>>;
  endings: Partial<Record<EndingId, { title: string; text: string }>>;
  truthSummary?: string;
  truthTimeline?: { time: string; event: string; cards: string }[];
  afterword?: string;
}

