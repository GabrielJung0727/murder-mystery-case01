export type NpcState = 0 | 1 | 2;

export interface Reaction {
  /** 제시한 카드 묶음에 모두 포함되어야 하는 카드 */
  cards: CardId[];
  minState?: NpcState;
  maxState?: NpcState;
  requiresFlags?: string[];
  /** 상태 전이 (현재보다 높을 때만 적용) */
  next?: NpcState;
  /** 해당 카드를 공용 보드에 강제 공개 */
  forceReveal?: CardId;
  /** 상태 전이 없이도 NPC 손패의 은폐 카드를 모두 공개 */
  releaseHidden?: boolean;
  setFlags?: string[];
  /** 진범 자백 (사건 해결 플래그) */
  solved?: boolean;
  tone: string;
  text: string;
  hint?: string;
}

export interface NpcScript {
  char: CharId;
  hiddenPriority: CardId[];
  states: Record<NpcState, { label: string; line: string }>;
  reactions: Reaction[];
  /** 매칭되는 반응이 없을 때 */
  fallback: string;
}

